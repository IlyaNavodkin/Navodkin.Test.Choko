import { act, cleanup, fireEvent, render, renderHook, screen, waitFor } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { filterGlossary, glossaryFixtures } from '../src/ux-preview/useCases/manage-glossary/fixtures';
import { glossarySchema } from '../src/ux-preview/useCases/manage-glossary/schema';
import { usePreviewWorkspace } from '../src/ux-preview/useCases/explore-design/usePreviewWorkspace';
import { GlossaryWorkspace } from '../src/ux-preview/useCases/manage-glossary/GlossaryWorkspace';
afterEach(cleanup);
describe('glossary preview', () => {
  it('connects distinct field errors and the alias hint to their controls', async () => {
    function Workspace() { const model = usePreviewWorkspace(); return <GlossaryWorkspace model={model.glossaryModel} />; }
    render(<Workspace />);
    expect(screen.getByRole('heading', { name: 'Альтернативные названия' })).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: 'Создать запись' }));
    const title = screen.getByRole('textbox', { name: 'Название' });
    const description = screen.getByRole('textbox', { name: 'Описание' });
    const url = screen.getByRole('textbox', { name: 'URL документа' });
    const aliases = screen.getByRole('textbox', { name: 'Альтернативные названия' });
    expect(document.getElementById(aliases.getAttribute('aria-describedby')!)?.textContent).toBe('Укажите через запятую');
    fireEvent.click(screen.getByRole('button', { name: 'Сохранить в демо' }));
    await waitFor(() => expect(title.getAttribute('aria-invalid')).toBe('true'));
    const titleErrorId = title.getAttribute('aria-describedby')!;
    const descriptionErrorId = description.getAttribute('aria-describedby')!;
    expect(titleErrorId).not.toBe(descriptionErrorId);
    expect(document.getElementById(titleErrorId)?.textContent).toBe('Укажите название');
    expect(document.getElementById(descriptionErrorId)?.textContent).toBe('Добавьте описание или URL');
    fireEvent.change(url, { target: { value: 'javascript:alert(1)' } });
    fireEvent.click(screen.getByRole('button', { name: 'Сохранить в демо' }));
    await waitFor(() => expect(url.getAttribute('aria-invalid')).toBe('true'));
    expect(document.getElementById(url.getAttribute('aria-describedby')!)?.textContent).toBe('Укажите корректный HTTP(S) URL');
    expect(screen.getByRole('textbox', { name: 'URL документа' })).toBe(url);
  });
  it('searches aliases and descriptions with combined type and archive filters', () => {
    const entries = glossaryFixtures(0);
    expect(filterGlossary(entries, { search: 'система быстрых', kind: 'abbreviation', archive: 'active' }).map((item) => item.title)).toEqual(['СБП']);
    expect(filterGlossary(entries, { search: 'доступности', kind: 'term', archive: 'active' }).map((item) => item.title)).toEqual(['SLA']);
    expect(filterGlossary(entries, { search: 'SLA', kind: 'document', archive: 'all' })).toEqual([]);
  });
  it('rejects blank titles, missing content and unsafe or malformed URLs', () => {
    const valid = { title: 'API', kind: 'term', aliases: '', description: '', url: 'https://example.com/docs', values: '' };
    expect(glossarySchema.safeParse(valid).success).toBe(true);
    for (const patch of [{ title: ' ' }, { url: '' }, { url: 'javascript:alert(1)' }, { url: 'file:///secret' }, { url: 'https://' }]) expect(glossarySchema.safeParse({ ...valid, ...patch }).success).toBe(false);
    for (const patch of [{ values: 'baseUrl=https://example.com' }, { values: '=' }, { values: 'no-separator' }]) expect(glossarySchema.safeParse({ ...valid, ...patch }).success).toBe(false);
    expect(glossarySchema.safeParse({ ...valid, kind: 'environment', values: 'baseUrl=https://example.com\nretries=2' }).success).toBe(true);
    expect(glossarySchema.safeParse({ ...valid, kind: 'environment', values: 'duplicate=1\nduplicate=2' }).success).toBe(false);
    expect(glossarySchema.safeParse({ ...valid, kind: 'environment', values: '' }).success).toBe(false);
  });
  it('creates and edits explicitly with stable UUID, and retains invalid drafts', async () => {
    const { result } = renderHook(() => usePreviewWorkspace());
    act(() => result.current.chromeModel.openRepository(0));
    act(() => result.current.glossaryModel.create());
    await act(async () => { expect(await result.current.glossary.save()).toBe(false); });
    expect(result.current.glossary.entries).toHaveLength(6);
    act(() => { result.current.glossary.update('title', 'Новый термин'); result.current.glossary.update('description', 'Пояснение'); });
    await act(async () => { expect(await result.current.glossary.save()).toBe(true); });
    const id = result.current.glossary.selected!.id;
    expect(id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Переименован'); });
    await act(async () => { await result.current.glossary.save(); });
    expect(result.current.glossary.selected?.id).toBe(id);
    expect(result.current.glossary.selected?.title).toBe('Переименован');
  });
  it('archives and restores content without deleting the entry', async () => {
    const { result } = renderHook(() => usePreviewWorkspace());
    const original = result.current.glossary.selected!;
    await act(async () => { await result.current.glossary.toggleArchive(); });
    expect(result.current.glossary.visibleEntries.some((entry) => entry.id === original.id)).toBe(false);
    act(() => result.current.glossary.setFilters({ search: '', kind: '', archive: 'archived' }));
    expect(result.current.glossary.visibleEntries).toEqual([{ ...original, archived: true }]);
    await act(async () => { await result.current.glossary.toggleArchive(); });
    expect(result.current.glossary.entries.find((entry) => entry.id === original.id)).toEqual(original);
  });
  it('protects dirty selection/create and global navigation with cancel, save and discard', async () => {
    const { result } = renderHook(() => usePreviewWorkspace());
    act(() => { result.current.chromeModel.openRepository(0); result.current.chromeModel.setSection('glossary'); });
    const id = result.current.glossary.selected!.id;
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Изменено'); });
    act(() => result.current.glossaryModel.selectEntry(result.current.glossary.entries[1].id));
    expect(result.current.navigation.open).toBe(true); expect(result.current.glossary.selected?.id).toBe(id);
    act(() => result.current.navigation.cancel());
    act(() => result.current.glossaryModel.create()); expect(result.current.navigation.open).toBe(true);
    act(() => result.current.navigation.cancel());
    act(() => result.current.chromeModel.setSection('git'));
    await act(async () => { await result.current.navigation.saveAndContinue(); });
    expect(result.current.model.section).toBe('git'); expect(result.current.glossary.selected?.title).toBe('Изменено');
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Отмена'); });
    act(() => result.current.closeSimulation());
    act(() => result.current.navigation.discardAndContinue());
    expect(result.current.closed).toBe(true); expect(result.current.glossary.selected?.title).toBe('Изменено');
  });
  it('retains failed draft, blocks writes in readonly and isolates repository state', async () => {
    const { result } = renderHook(() => usePreviewWorkspace());
    act(() => result.current.chromeModel.openRepository(0));
    const original = result.current.glossary.selected!.title;
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Изменено'); });
    act(() => result.current.chooseState('saveFailed'));
    act(() => result.current.navigation.cancel());
    await act(async () => { expect(await result.current.glossary.save()).toBe(false); });
    expect(result.current.glossary.dirty).toBe(true); expect(result.current.glossary.selected?.title).toBe(original);
    act(() => result.current.resetState());
    await act(async () => { await result.current.glossary.save(); });
    act(() => result.current.chromeModel.openRepository(1));
    expect(result.current.glossary.entries.map((entry) => entry.title)).toEqual(['Мобильная сессия', 'Локальный стенд']);
    act(() => result.current.chromeModel.openRepository(0));
    expect(result.current.glossary.selected?.title).toBe('Изменено');
    act(() => result.current.chooseState('readonly'));
    const saved = result.current.glossary.entries;
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Нельзя'); result.current.glossaryModel.create(); });
    await act(async () => { expect(await result.current.glossary.toggleArchive()).toBe(false); });
    expect(result.current.glossary.entries).toEqual(saved);
  });
  it('keeps hidden selection and dirty input when filters exclude the selected entry', () => {
    const { result } = renderHook(() => usePreviewWorkspace());
    const id = result.current.glossary.selected!.id;
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Черновик'); });
    act(() => result.current.glossary.setFilters({ search: 'Нет совпадений', kind: 'document', archive: 'archived' }));
    expect(result.current.glossary.visibleEntries).toEqual([]);
    expect(result.current.glossary.selected?.id).toBe(id);
    expect(result.current.glossary.values.title).toBe('Черновик');
    expect(result.current.glossary.dirty).toBe(true);
  });
  it('keeps failed navigation open, isolates selected drafts and guards restart', async () => {
    const onRestart = vi.fn();
    const { result } = renderHook(() => usePreviewWorkspace({ onRestart }));
    act(() => result.current.chromeModel.openRepository(0));
    act(() => result.current.chooseState('saveFailed'));
    act(() => { result.current.glossary.edit(); result.current.glossary.update('title', 'Черновик A'); });
    act(() => result.current.chromeModel.openRepository(1));
    await act(async () => { await result.current.navigation.saveAndContinue(); });
    expect(result.current.navigation.open).toBe(true);
    expect(result.current.navigation.error).not.toBe('');
    expect(result.current.model.repository).toBe(0);
    expect(result.current.glossary.values.title).toBe('Черновик A');
    act(() => result.current.navigation.discardAndContinue());
    expect(result.current.model.repository).toBe(1);
    expect(result.current.glossary.editing).toBe(false);
    act(() => { result.current.glossaryModel.create(); result.current.glossary.update('title', 'Черновик B'); });
    act(() => result.current.restartDemo());
    expect(onRestart).not.toHaveBeenCalled();
    act(() => result.current.navigation.cancel());
    expect(result.current.glossary.values.title).toBe('Черновик B');
    act(() => result.current.chromeModel.openRepository(0));
    act(() => result.current.navigation.discardAndContinue());
    expect(result.current.glossary.selected?.title).toBe('SLA');
    act(() => result.current.chromeModel.openRepository(1));
    expect(result.current.glossary.newId).toBeNull();
    expect(result.current.glossary.values.title).not.toBe('Черновик A');
    act(() => result.current.restartDemo());
    expect(onRestart).toHaveBeenCalledOnce();
  });
});
