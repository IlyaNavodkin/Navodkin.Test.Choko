type IconRenderer = (props: LucideProps) => ReactNode;

function SignalBars({
  bars,
  size,
  absoluteStrokeWidth: _absoluteStrokeWidth,
  ...props
}: LucideProps & { bars: 1 | 2 | 3 }) {
  return (
    <svg {...props} width={size} height={size} viewBox="0 0 24 24" fill="none">
      <rect x="3" y="14" width="4" height="7" rx="1" fill="currentColor" />
      {bars >= 2 && <rect x="10" y="10" width="4" height="11" rx="1" fill="currentColor" />}
      {bars >= 3 && <rect x="17" y="5" width="4" height="16" rx="1" fill="currentColor" />}
    </svg>
  );
}

/** Application-owned SVGs so connection strength is independent of an icon vendor. */
function SignalStrengthOne(props: LucideProps) {
  return <SignalBars {...props} bars={1} />;
}

function SignalStrengthTwo(props: LucideProps) {
  return <SignalBars {...props} bars={2} />;
}

function SignalStrengthThree(props: LucideProps) {
  return <SignalBars {...props} bars={3} />;
}

